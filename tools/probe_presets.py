"""Generate and check the Scratch 2.0 preset apply probe.

Compiles two one-sprite preset change sets through the real bridge path
(schema -> media resolution -> validation -> changeset literal) and writes
``scratch/base/probes/probe_presets_apply.st`` for the running image.

The generated probe applies one copied-PNG preset (``Dog Puppy``) and one
SVG-rasterized preset (``0-Glow``), logs costumes and rotation centres, then
undoes both. Run it through the control server:

    python tools/probe_presets.py
    python tools/ai_control.py load <absolute path to the probe>

The image probe is deliberately ASCII/Smalltalk only; all asset and rotation
centre data comes from ``Media/Scratch2/sprites.json``.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "bridge" / "src"))

from harness.block_ir import ChangeSet  # noqa: E402
from harness.changeset import compile_changeset  # noqa: E402
from harness.context import ProjectContext  # noqa: E402
from harness.protocol import Sym, parse_literal  # noqa: E402
from harness.validator import validate_changeset  # noqa: E402

PROBE_PATH = ROOT / "scratch" / "base" / "probes" / "probe_presets_apply.st"

DOG = "Dog Puppy"
GLOW = "0-Glow"


def smalltalk_string(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def build_literal(name: str, preset: str, request_id: int) -> str:
    changeset = ChangeSet.from_dict(
        {
            "summary": f"preset probe: {preset}",
            "changes": [{"action": "create_sprite", "name": name, "preset": preset}],
        }
    )
    context = ProjectContext.demo()
    issues = validate_changeset(changeset, context)
    if issues:
        detail = "; ".join(f"{issue.path}: {issue.message}" for issue in issues)
        raise SystemExit(f"preset {preset!r} failed validation: {detail}")
    return compile_changeset(changeset, context).apply_literal(request_id)


def check_literal(literal: str, preset: str) -> None:
    message = parse_literal(literal)
    create = message[2][0]
    assert create[0] == Sym("createSprite"), create
    assert create[1].startswith("Preset"), create
    costumes = create[2]
    if preset == DOG:
        assert len(costumes) == 4, "Dog Puppy should carry four costumes"
        # Copied PNG centres from the manifest (bitmap pixels).
        assert tuple(costumes[0][2:4]) == (107.0, 103.0), costumes[0]
        assert tuple(costumes[3][2:4]) == (234.0, 94.0), costumes[3]
    elif preset == GLOW:
        assert len(costumes) == 1, "0-Glow should carry one costume"
        # SVG-rasterized costume centre is scaled to the 2x bitmap.
        assert tuple(costumes[0][2:4]) == (58.0, 78.0), costumes[0]
    print(f"{preset}: costumes={[item[1] for item in costumes]}")


def build_probe(dog_literal: str, glow_literal: str) -> str:
    return f'''"Preset apply probe generated by tools/probe_presets.py.
Applies a copied-PNG preset and an SVG-rasterized preset, checks costumes and
rotation centres, then undoes both. Does not save the image."
| a d g dogSprite glowSprite |
a := Smalltalk at: #AIHarness.
d := (Smalltalk at: #AILiteralReader) parse: {smalltalk_string(dog_literal)}.
a logLine: 'PPRESET dog apply=', ((Smalltalk at: #AIChangeSetApplier) apply: (d at: 3)) printString.
g := (Smalltalk at: #AILiteralReader) parse: {smalltalk_string(glow_literal)}.
a logLine: 'PPRESET glow apply=', ((Smalltalk at: #AIChangeSetApplier) apply: (g at: 3)) printString.
dogSprite := (Smalltalk at: #AIChangeSetApplier) targetNamed: 'PresetDog'.
glowSprite := (Smalltalk at: #AIChangeSetApplier) targetNamed: 'PresetGlow'.
dogSprite ifNil: [a logLine: 'PPRESET dog missing'] ifNotNil: [
    a logLine: 'PPRESET dog costumes=', dogSprite costumeNames asArray printString,
        ' props=', ((Smalltalk at: #AIChangeSetApplier) spritePropsFor: 'PresetDog') printString,
        ' center1=', dogSprite costume rotationCenter printString,
        ' centerLast=', dogSprite media last rotationCenter printString].
glowSprite ifNil: [a logLine: 'PPRESET glow missing'] ifNotNil: [
    a logLine: 'PPRESET glow costumes=', glowSprite costumeNames asArray printString,
        ' center=', glowSprite costume rotationCenter printString].
a logLine: 'PPRESET undo=', ((Smalltalk at: #AIChangeSetApplier) undoLast) printString,
    ' then=', ((Smalltalk at: #AIChangeSetApplier) undoLast) printString,
    ' dog=', ((Smalltalk at: #AIChangeSetApplier) targetNamed: 'PresetDog') printString,
    ' glow=', ((Smalltalk at: #AIChangeSetApplier) targetNamed: 'PresetGlow') printString.
'''


def main() -> None:
    dog_literal = build_literal("PresetDog", DOG, 91)
    glow_literal = build_literal("PresetGlow", GLOW, 92)
    check_literal(dog_literal, DOG)
    check_literal(glow_literal, GLOW)
    PROBE_PATH.write_text(build_probe(dog_literal, glow_literal), encoding="ascii")
    print("wrote", PROBE_PATH)


if __name__ == "__main__":
    main()
